const COLLECTION_ITEM_BY_ID = new Map(COLLECTION_ITEMS.map((item) => [item.id, item]));
const DUPLICATE_COIN_REWARD = 3;

function getCollectionItemById(id) {
  return COLLECTION_ITEM_BY_ID.get(id) ?? null;
}

function drawRandomCollectionItem() {
  return COLLECTION_ITEMS[Math.floor(Math.random() * COLLECTION_ITEMS.length)];
}

